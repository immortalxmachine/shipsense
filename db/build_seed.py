"""Generate db/seed.sql from the REAL Olist dataset + Brazilian geography.

Hubs are the 27 federative units (centroids from the real geolocation data),
routes are the real border adjacency weighted by great-circle distance, and the
sample shipments + tracking events are a real, reproducible sample of actual
Olist orders (real purchase/estimate/delivery timestamps). Nothing is invented;
``avg_travel_hours`` is the one transparent estimate (distance / assumed road
speed), matching the ML service's routing assumption.

Run (from repo root):
    python db/build_seed.py --olist data/olist --out db/seed.sql
"""
from __future__ import annotations

import argparse
import os
import sys

import pandas as pd

# Reuse the shared geography module from the ML service.
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "ml-service"))
from pipeline.geo import (  # noqa: E402
    ASSUMED_ROAD_KMH, STATE_NAME, STATE_REGION, border_edges, haversine_km, state_centroids,
)

N_DELIVERED = 10   # real delivered sample orders
N_IN_TRANSIT = 4   # real not-yet-delivered sample orders


def q(s: str) -> str:
    """SQL-escape a string literal."""
    return s.replace("'", "''")


def _load_orders(olist_dir: str) -> pd.DataFrame:
    orders = pd.read_csv(
        os.path.join(olist_dir, "olist_orders_dataset.csv"),
        usecols=["order_id", "customer_id", "order_status",
                 "order_purchase_timestamp", "order_approved_at",
                 "order_delivered_carrier_date", "order_delivered_customer_date",
                 "order_estimated_delivery_date"],
    )
    items = pd.read_csv(
        os.path.join(olist_dir, "olist_order_items_dataset.csv"),
        usecols=["order_id", "product_id", "seller_id", "freight_value"],
    )
    customers = pd.read_csv(os.path.join(olist_dir, "olist_customers_dataset.csv"),
                            usecols=["customer_id", "customer_state"])
    sellers = pd.read_csv(os.path.join(olist_dir, "olist_sellers_dataset.csv"),
                          usecols=["seller_id", "seller_state"])
    products = pd.read_csv(os.path.join(olist_dir, "olist_products_dataset.csv"),
                           usecols=["product_id", "product_weight_g"])

    item_agg = items.groupby("order_id").agg(
        freight_value=("freight_value", "sum"),
        seller_id=("seller_id", "first"),
    ).reset_index()
    iw = items.merge(products, on="product_id", how="left")
    weight_agg = (iw.groupby("order_id")["product_weight_g"].sum().div(1000.0)
                  .rename("weight_kg").reset_index())

    df = (orders.merge(item_agg, on="order_id", how="inner")
          .merge(weight_agg, on="order_id", how="left")
          .merge(customers, on="customer_id", how="left")
          .merge(sellers, on="seller_id", how="left"))
    # Cross-state only (origin must differ from destination) with a real weight.
    df = df[(df.seller_state != df.customer_state) & (df.weight_kg > 0)
            & df.seller_state.notna() & df.customer_state.notna()]
    df = df[df.seller_state.isin(STATE_NAME) & df.customer_state.isin(STATE_NAME)]
    return df


def build_sql(olist_dir: str) -> str:
    cent = state_centroids(os.path.join(olist_dir, "olist_geolocation_dataset.csv"))
    df = _load_orders(olist_dir)

    delivered = df[(df.order_status == "delivered")
                   & df.order_delivered_customer_date.notna()]
    in_transit = df[df.order_status.isin(["shipped", "processing", "invoiced"])
                    & df.order_delivered_customer_date.isna()]

    samp_d = delivered.sample(n=N_DELIVERED, random_state=42).reset_index(drop=True)
    samp_t = in_transit.sample(n=min(N_IN_TRANSIT, len(in_transit)),
                               random_state=42).reset_index(drop=True)

    out: list[str] = []
    out.append("-- ===========================================================================")
    out.append("-- ShipSense — seed data  (GENERATED by db/build_seed.py — do not edit by hand)")
    out.append("-- ---------------------------------------------------------------------------")
    out.append("-- Source: Olist Brazilian E-Commerce Public Dataset")
    out.append("--   (Kaggle: olistbr/brazilian-ecommerce, CC BY-NC-SA 4.0).")
    out.append("--")
    out.append("-- Hubs       : 27 Brazilian federative units; lat/lng are the mean of the")
    out.append("--              real geolocation points per state.")
    out.append("-- Routes     : real land-border adjacency; distance_km = great-circle between")
    out.append(f"--              state centroids; avg_travel_hours = distance / {ASSUMED_ROAD_KMH:.0f} km/h")
    out.append("--              (a transparent estimate, the only non-measured value here).")
    out.append("-- Shipments  : a real, reproducible sample of actual Olist orders — real")
    out.append("--              purchase/estimate/delivery timestamps, weights and freight.")
    out.append("-- ===========================================================================")
    out.append("")

    # ---- Hubs ----------------------------------------------------------------
    out.append("-- Hubs  (code, name, city, region, lat, lng)")
    out.append("INSERT INTO hubs (code, name, city, region, lat, lng) VALUES")
    rows = []
    for uf in STATE_NAME:
        if uf not in cent.index:
            continue
        lat, lng = cent.loc[uf, "lat"], cent.loc[uf, "lng"]
        name = f"{STATE_NAME[uf]} Hub"
        rows.append(f"  ('{uf}', '{q(name)}', '{q(STATE_NAME[uf])}', "
                    f"'{STATE_REGION[uf]}', {lat:.6f}, {lng:.6f})")
    out.append(",\n".join(rows) + ";")
    out.append("")

    # ---- Routes --------------------------------------------------------------
    out.append("-- Routes  (real border adjacency, inserted as BOTH directed edges)")
    out.append("WITH edge(a, b, km, hrs) AS (")
    out.append("  VALUES")
    erows = []
    for a, b in border_edges():
        if a not in cent.index or b not in cent.index:
            continue
        km = haversine_km(cent.loc[a, "lat"], cent.loc[a, "lng"],
                          cent.loc[b, "lat"], cent.loc[b, "lng"])
        hrs = km / ASSUMED_ROAD_KMH
        erows.append(f"    ('{a}','{b}', {km:7.1f}, {hrs:5.1f})")
    out.append(",\n".join(erows))
    out.append(")")
    out.append("INSERT INTO routes (from_hub, to_hub, distance_km, avg_travel_hours)")
    out.append("SELECT ha.id, hb.id, e.km, e.hrs")
    out.append("  FROM edge e JOIN hubs ha ON ha.code = e.a JOIN hubs hb ON hb.code = e.b")
    out.append("UNION ALL")
    out.append("SELECT hb.id, ha.id, e.km, e.hrs")
    out.append("  FROM edge e JOIN hubs ha ON ha.code = e.a JOIN hubs hb ON hb.code = e.b;")
    out.append("")

    # ---- Shipments -----------------------------------------------------------
    def ts(v) -> str:
        return "NULL" if pd.isna(v) else f"'{v}'"

    out.append("-- Sample shipments  (each row is a real Olist order; see order_id comment)")
    out.append("INSERT INTO shipments")
    out.append("    (tracking_no, origin_hub, dest_hub, weight_kg, freight_value, status,")
    out.append("     created_at, promised_at, delivered_at)")
    out.append("SELECT s.tracking_no, ho.id, hd.id, s.weight_kg, s.freight_value, s.status,")
    out.append("       s.created_at, s.promised_at, s.delivered_at")
    out.append("FROM (")
    out.append("    VALUES")
    # Each entry is (value_tuple_sql, trailing_comment) so the row-separating
    # comma can go BEFORE the "-- ..." comment (otherwise the comment eats it).
    srows: list[tuple[str, str]] = []
    idx = 1
    shipment_meta = []  # (tracking_no, order row) for tracking events
    for _, r in samp_d.iterrows():
        tn = f"SS{idx:010d}"
        late = pd.notna(r.order_delivered_customer_date) and pd.notna(r.order_estimated_delivery_date) \
            and r.order_delivered_customer_date > r.order_estimated_delivery_date
        srows.append((
            f"('{tn}','{r.seller_state}','{r.customer_state}', {r.weight_kg:.2f}, "
            f"{r.freight_value:.2f}, 'DELIVERED', '{r.order_purchase_timestamp}', "
            f"'{r.order_estimated_delivery_date}', '{r.order_delivered_customer_date}')",
            f"order {r.order_id[:12]}…{' (delivered late)' if late else ''}",
        ))
        shipment_meta.append((tn, r))
        idx += 1
    for _, r in samp_t.iterrows():
        tn = f"SS{idx:010d}"
        srows.append((
            f"('{tn}','{r.seller_state}','{r.customer_state}', {r.weight_kg:.2f}, "
            f"{r.freight_value:.2f}, 'IN_TRANSIT', '{r.order_purchase_timestamp}', "
            f"'{r.order_estimated_delivery_date}', NULL)",
            f"order {r.order_id[:12]}… (not yet delivered)",
        ))
        idx += 1
    for i, (val, comment) in enumerate(srows):
        sep = "," if i < len(srows) - 1 else ""
        out.append(f"      {val}{sep}  -- {comment}")
    out.append(") AS s(tracking_no, o_code, d_code, weight_kg, freight_value, status,")
    out.append("       created_at, promised_at, delivered_at)")
    out.append("JOIN hubs ho ON ho.code = s.o_code")
    out.append("JOIN hubs hd ON hd.code = s.d_code;")
    out.append("")

    # ---- Tracking events (real timestamps) for the first 3 delivered orders --
    out.append("-- Tracking events for a few shipments (real Olist timestamps).")
    out.append("-- We only know the origin (seller) and destination (customer) states, so the")
    out.append("-- scan history reflects exactly those hops — no intermediate hub is invented.")
    for tn, r in shipment_meta[:3]:
        events = []
        if pd.notna(r.order_approved_at):
            events.append((r.seller_state, "PICKED_UP", r.order_approved_at))
        if pd.notna(r.order_delivered_carrier_date):
            events.append((r.seller_state, "DEPARTED_HUB", r.order_delivered_carrier_date))
            events.append((r.customer_state, "ARRIVED_AT_HUB", r.order_delivered_carrier_date))
        if pd.notna(r.order_delivered_customer_date):
            events.append((r.customer_state, "OUT_FOR_DELIVERY", r.order_delivered_customer_date))
            events.append((r.customer_state, "DELIVERED", r.order_delivered_customer_date))
        if not events:
            continue
        out.append("INSERT INTO tracking_events (shipment_id, hub_id, event_type, event_time)")
        out.append("SELECT s.id, h.id, e.event_type, e.event_time")
        out.append("FROM shipments s")
        out.append("JOIN (")
        out.append("    VALUES")
        evrows = [f"      ('{st}','{et}', '{tm}')" for st, et, tm in events]
        out.append(",\n".join(evrows))
        out.append(") AS e(hub_code, event_type, event_time) ON TRUE")
        out.append("JOIN hubs h ON h.code = e.hub_code")
        out.append(f"WHERE s.tracking_no = '{tn}';")
        out.append("")

    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate db/seed.sql from real Olist data.")
    parser.add_argument("--olist", default=os.getenv("OLIST_DIR", "data/olist"))
    parser.add_argument("--out", default="db/seed.sql")
    args = parser.parse_args()
    sql = build_sql(args.olist)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(sql + "\n")
    print(f"Wrote {args.out} ({len(sql.splitlines())} lines)")


if __name__ == "__main__":
    main()
